"""The app recipes and the official listings, built into the program rather than shipped as readable files (18 Oct 2026: "build them into the program"). Each file is compressed (raw DEFLATE), mixed with a fixed key and kept
as base64 text in a Swift source, so the app bundle carries no loose JSON. The JSON files under Resources/ are the
source; EmbeddedResources.swift is generated from them and is never edited by hand.

    python3 make-embedded.py            writes Sources/Core/EmbeddedResources.swift
"""
import base64, glob, os, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
KEY = b"TurnOver/embedded/2026"
OUT = os.path.join(HERE, "Sources", "Core", "EmbeddedResources.swift")


def pack(path):
    raw = open(path, "rb").read()
    c = zlib.compressobj(9, zlib.DEFLATED, -15)
    data = c.compress(raw) + c.flush()
    mixed = bytes(b ^ KEY[i % len(KEY)] for i, b in enumerate(data))
    return base64.b64encode(mixed).decode("ascii")


def entries(folder):
    files = sorted(glob.glob(os.path.join(HERE, "Resources", folder, "*.json")))
    return [(os.path.basename(f), pack(f)) for f in files]


def swift_list(items):
    return ",\n".join(f'        ("{n}", "{b}")' for n, b in items)


recipes, official, keymaps = entries("recipes"), entries("official"), entries("keymaps")
key = ", ".join(str(b) for b in KEY)
src = f'''// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by make-embedded.py from Resources/recipes, Resources/official and Resources/keymaps; don't edit by hand.
// The built-in app recipes and the official listings, compressed and mixed so they aren't readable files in the app.
import Foundation

enum EmbeddedResources {{
    static let recipes: [(name: String, packed: String)] = [
{swift_list(recipes)}
    ]
    static let official: [(name: String, packed: String)] = [
{swift_list(official)}
    ]
    static let keymaps: [(name: String, packed: String)] = [
{swift_list(keymaps)}
    ]
    private static let key: [UInt8] = [{key}]

    /// A packed file back to its bytes: base64, unmixed, inflated.
    static func unpack(_ packed: String) -> Data? {{
        guard let mixed = Data(base64Encoded: packed) else {{ return nil }}
        let raw = Data(mixed.enumerated().map {{ $1 ^ key[$0 % key.count] }})
        return try? (raw as NSData).decompressed(using: .zlib) as Data
    }}
}}
'''
open(OUT, "w", encoding="utf-8").write(src)
print(f"make-embedded: {len(recipes)} recipes, {len(official)} official listings, {len(keymaps)} keymaps")
